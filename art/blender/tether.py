# tether.py: the line weapons' rope links as Blender meshes (list-combat 2026-11-20, Everything Left 392: "The tether
# and rope links are plain links (no rope model)"). Fx.TetherFx stretches one mesh over each segment of the swinging
# line (Shared.TetherMath: SPECS[id].link), along z, its width the line's:
#   TetherRope    a three-strand twisted rope with two full twists, 1 x 1 x 1 (the Rope Dart's rope, the Yo-yo's string)
#   TetherChain   three interlocked oval chain links, each turned 90 degrees from the last, 1 x 1 x 1 (the Chain Whip)
# Output: art/export/Tether.fbx and src/config/TetherArt.luau (generated); --preview renders art/preview/tether.png.
# Run: ~/tools/bpyenv/bin/python art/blender/tether.py [--preview] [--no-export]
import math
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(__file__))
import kit  # noqa: E402
import bpy  # noqa: E402,F401
from mathutils import Vector  # noqa: E402

kit.reset()
from studs import *  # noqa: E402,F401,F403
from studs import LOOKS, INFO  # noqa: E402


def rope():
    parts = []
    for s in range(3):
        pts = []
        for k in range(49):
            t = k / 48
            a = 2 * math.pi * s / 3 + t * 2 * math.pi * 2
            pts.append((math.cos(a) * 0.2, math.sin(a) * 0.2, -0.5 + t))
        parts.append(T(pts, 0.19, segs=8))
    mesh("Tether", "TetherRope", parts, (210, 180, 120), "Fabric")


def chain():
    parts = []
    n = 3
    step = 1.0 / n
    for i in range(n):
        z = -0.5 + step * (i + 0.5)
        # an oval link: a torus squashed along z, alternate links turned 90 degrees about z
        ring = TOR(0.17, 0.06, 0, 0, 0, axis="x", segs=20, csegs=6)
        kit.apply_all(ring)
        for v in ring.data.vertices:
            v.co.y *= 1.6  # Blender y is Roblox -z: stretch along the chain
        ring.data.update()
        if i % 2 == 1:
            turn(ring, "z", 90)
        shift(ring, rb(0, 0, z))
        parts.append(ring)
    mesh("Tether", "TetherChain", parts, (200, 200, 210), "Metal")


rope()
chain()


def bounds(ob):
    vs = [ob.matrix_world @ v.co for v in ob.data.vertices]
    lo = Vector((min(v.x for v in vs), min(v.y for v in vs), min(v.z for v in vs)))
    hi = Vector((max(v.x for v in vs), max(v.y for v in vs), max(v.z for v in vs)))
    return lo, hi


rows = []
total = 0
for look in sorted(LOOKS):
    for name in sorted(LOOKS[look]):
        ob = LOOKS[look][name]
        lo, hi = bounds(ob)
        size = hi - lo
        t = kit.tris(ob)
        total += t
        rows.append('\t%s = { size = { %.3f, %.3f, %.3f }, tris = %d },' % (name, size.x, size.z, size.y, t))
text = "\n".join([
    "-- GENERATED by art/blender/tether.py: do not edit by hand.",
    "-- The line weapons' rope links as meshes (ReplicatedStorage.Art.Tether, Fx.TetherFx): each segment's mesh, drawn",
    "-- along z (x, up, z) and stretched over the segment, and its triangles. %d meshes, %d triangles." % (len(INFO), total),
    "return {",
] + rows + ["}", ""])
FIT = os.path.normpath(os.path.join(kit.ROOT, "..", "src", "config", "TetherArt.luau"))
with open(FIT, "w") as f:
    f.write(text)
_stylua = shutil.which("stylua") or os.path.expanduser("~/tools/stylua")
if os.path.exists(_stylua):
    subprocess.run([_stylua, "--config-path", os.path.join(os.path.dirname(FIT), "..", "..", "stylua.toml"), FIT],
                   check=False)
print("tether: %d meshes, %d tris" % (len(INFO), total))

if "--no-export" not in sys.argv:
    export = []
    for look in LOOKS:
        for name, ob in LOOKS[look].items():
            cp = copy(ob)
            kit.centre(cp)
            cp.name = name
            cp.data.name = name
            export.append(cp)
    kit.export_fbx(export, os.path.join(kit.ROOT, "export", "Tether.fbx"))
    for cp in export:
        bpy.data.objects.remove(cp, do_unlink=True)

if "--preview" in sys.argv:
    kit.studio(res=(1200, 500), samples=32)
    G = LOOKS["Tether"]
    G["TetherRope"].data.materials.append(kit.material("r", (210, 180, 120)))
    G["TetherChain"].data.materials.append(kit.material("c", (200, 200, 210), metal=0.8, rough=0.3))
    # a few segments laid end to end along x, as the game chains them
    for name, y in (("TetherRope", 1.2), ("TetherChain", -1.2)):
        src = G[name]
        for k in range(5):
            o = src if k == 0 else copy(src)
            o.rotation_euler = (0, 0, math.radians(90))
            o.location = (-4 + k * 1.0, y * 0.8, 1.5)
            o.scale = (0.35, 1.0, 0.35)
    ground = kit.box("ground", 40, 20, 0.2, at=(0, 0, -0.1))
    ground.data.materials.append(kit.material("g", (150, 150, 158)))
    kit.camera((-2, -7, 4), (-2, 0, 1.4), lens=40)
    kit.render(os.path.join(kit.ROOT, "preview", "tether.png"))
