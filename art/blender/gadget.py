# gadget.py: the Shield Drone gadget as Blender meshes (list-combat 2026-11-20, Everything Left 383: "Gadgets: the
# shield drone is plain parts"). Fx.GadgetFx flies them round the owner (its shield bubble is Art.Guard's geodesic
# bubble). Drawn in Roblox's frame (x, up, z; front -z, toward the owner it watches):
#   GadgetDroneBody   a white rounded pod with a lens ring on its front, a fin on top and two arms out to motor pods,
#                     1.8 x 0.8 x 1.1 (its glowing lamp stays a Neon part in the lens, in the drone's colour)
#   GadgetRotor       a flat four-blade rotor with a hub, spun over the pod, 2.2 x 0.12 x 2.2
# Output: art/export/Gadget.fbx and src/config/GadgetArt.luau (generated); --preview renders art/preview/gadget.png.
# Run: ~/tools/bpyenv/bin/python art/blender/gadget.py [--preview] [--no-export]
import math
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(__file__))
import kit  # noqa: E402
import bpy  # noqa: E402,F401
from mathutils import Vector  # noqa: E402

kit.reset()
from studs import *  # noqa: E402,F401,F403
from studs import LOOKS, INFO  # noqa: E402


def body():
    parts = [S(0.5, 0, 0, 0, sc=(1.0, 0.75, 1.05), segs=18, rings=10)]
    parts.append(TOR(0.26, 0.05, 0, 0, -0.48, segs=18, csegs=6, axis="z"))  # the lens ring
    parts.append(B(0.08, 0.22, 0.5, 0, 0.36, 0.12, bev=0.03))  # a fin on top
    for sx in (-1, 1):
        parts.append(T([(sx * 0.4, 0, 0), (sx * 0.7, 0.05, 0), (sx * 0.78, 0.08, 0)], 0.06, segs=6))
        parts.append(C(0.13, 0.26, sx * 0.78, 0.0, 0, segs=12))  # the motor pod
    mesh("Drone", "GadgetDroneBody", parts, (235, 240, 248), "SmoothPlastic")


def rotor():
    parts = [C(0.14, 0.12, 0, 0, 0, segs=12)]
    for k in range(4):
        a = math.pi / 2 * k + math.pi / 4
        c, s = math.cos(a), math.sin(a)
        # a blade: a long thin quad, twisted a little (thicker at the root)
        tx, tz = -s, c
        poly = [(c * 0.12 + tx * 0.08, s * 0.12 + tz * 0.08), (c * 1.1 + tx * 0.12, s * 1.1 + tz * 0.12),
                (c * 1.1 - tx * 0.02, s * 1.1 - tz * 0.02), (c * 0.12 - tx * 0.08, s * 0.12 - tz * 0.08)]
        parts.append(extrude_up(poly, -0.03, 0.03))
    mesh("Drone", "GadgetRotor", parts, (60, 70, 90), "Metal", shade=False)


body()
rotor()


def bounds(ob):
    vs = [ob.matrix_world @ v.co for v in ob.data.vertices]
    lo = Vector((min(v.x for v in vs), min(v.y for v in vs), min(v.z for v in vs)))
    hi = Vector((max(v.x for v in vs), max(v.y for v in vs), max(v.z for v in vs)))
    return lo, hi


rows = []
total = 0
for look in sorted(LOOKS):
    for name in sorted(LOOKS[look]):
        ob = LOOKS[look][name]
        lo, hi = bounds(ob)
        size = hi - lo
        t = kit.tris(ob)
        total += t
        rows.append('\t%s = { size = { %.3f, %.3f, %.3f }, tris = %d },' % (name, size.x, size.z, size.y, t))
text = "\n".join([
    "-- GENERATED by art/blender/gadget.py: do not edit by hand.",
    "-- The Shield Drone gadget as meshes (ReplicatedStorage.Art.Gadget, Fx.GadgetFx): each mesh's size in studs (x, up,",
    "-- z) and its triangles. %d meshes, %d triangles." % (len(INFO), total),
    "return {",
] + rows + ["}", ""])
FIT = os.path.normpath(os.path.join(kit.ROOT, "..", "src", "config", "GadgetArt.luau"))
with open(FIT, "w") as f:
    f.write(text)
_stylua = shutil.which("stylua") or os.path.expanduser("~/tools/stylua")
if os.path.exists(_stylua):
    subprocess.run([_stylua, "--config-path", os.path.join(os.path.dirname(FIT), "..", "..", "stylua.toml"), FIT],
                   check=False)
print("gadget: %d meshes, %d tris" % (len(INFO), total))

if "--no-export" not in sys.argv:
    export = []
    for look in LOOKS:
        for name, ob in LOOKS[look].items():
            cp = copy(ob)
            kit.centre(cp)
            cp.name = name
            cp.data.name = name
            export.append(cp)
    kit.export_fbx(export, os.path.join(kit.ROOT, "export", "Gadget.fbx"))
    for cp in export:
        bpy.data.objects.remove(cp, do_unlink=True)

if "--preview" in sys.argv:
    kit.studio(res=(900, 600), samples=32)
    G = LOOKS["Drone"]
    G["GadgetDroneBody"].data.materials.append(kit.material("b", (235, 240, 248)))
    G["GadgetRotor"].data.materials.append(kit.material("r", (60, 70, 90), metal=0.6))
    G["GadgetRotor"].location = (0, 0, 0.55)
    lamp = kit.sphere("lamp", 0.17, at=rb(0, 0, -0.5))
    lamp.data.materials.append(kit.material("l", (120, 200, 255), emit=3.0))
    for o in (G["GadgetDroneBody"], G["GadgetRotor"], lamp):
        o.scale = (2, 2, 2)
        o.location = (o.location[0] * 2, o.location[1] * 2, o.location[2] * 2 + 2)
    ground = kit.box("ground", 30, 30, 0.2, at=(0, 0, -0.1))
    ground.data.materials.append(kit.material("g", (150, 150, 158)))
    kit.camera((3, 7, 4.5), (0, 0, 2), lens=40)  # from the front (Roblox -z is Blender +y)
    kit.render(os.path.join(kit.ROOT, "preview", "gadget.png"))
