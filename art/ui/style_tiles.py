# art/ui/style_tiles.py: the gear styles' picture tiles (list-combat 2026-11-20, Everything Left 362: "Style tiles in
# the STYLES tab are text only (no picture per style)"). Reads gear.py's renders of every look (THUMBS=1
# ~/tools/bpyenv/bin/python art/blender/gear.py --quick: art/thumbs/cells/gear_<slot>/<slot>~<shape>.png, not
# committed) and frames each as the creator's small comic card (a tinted card by slot with halftone dots, the piece
# with a thick ink outline, an ink border), packed 8 x 8 into one 1024 x 1024 sheet of 128 px cells:
# art/export/ui/styles/StyleTiles.png. Writes src/config/StyleTiles.luau (each look key "<slot>:<shape>" or
# "<slot>:set:<Set>" / "<slot>:gilded" -> its cell, the order Shared.GearMath.lookKey names them) and the preview
# art/preview/style_tiles.png. The sheet's uploaded id is Config.Ui.styleTiles (GearScreen's STYLES tab).
# Run from the repo root: python3 art/ui/style_tiles.py
import os
import subprocess
import shutil

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CELLS = os.path.join(ROOT, "art", "thumbs", "cells")
OUT = os.path.join(ROOT, "art", "export", "ui", "styles")
os.makedirs(OUT, exist_ok=True)
CELL, PER, SS = 128, 8, 2
INK = (17, 17, 17)
SLOTS = ("head", "chest", "hands", "legs", "feet", "back", "belt")
CARD = {"head": (255, 230, 196), "chest": (214, 232, 255), "hands": (220, 246, 220), "legs": (238, 224, 255),
        "feet": (255, 236, 170), "back": (255, 222, 222), "belt": (230, 236, 210)}


def card(img, slot):
    W = CELL * SS
    out = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    d = ImageDraw.Draw(out)
    tint = CARD[slot]
    d.rounded_rectangle([3, 3, W - 4, W - 4], radius=18, fill=tint + (255,))
    # halftone dots, heavier toward the bottom right
    dark = tuple(max(0, c - 34) for c in tint) + (255,)
    for y in range(10, W - 8, 12):
        for x in range(10, W - 8, 12):
            r = 1.0 + 2.6 * ((x + y) / (2 * W))
            d.ellipse([x - r, y - r, x + r, y + r], fill=dark)
    # the piece: fit its alpha box into the card, then a thick ink outline from its dilated alpha
    box = img.getchannel("A").getbbox()
    if box:
        img = img.crop(box)
    k = (W - 44) / max(img.size)
    img = img.resize((max(1, int(img.size[0] * k)), max(1, int(img.size[1] * k))), Image.LANCZOS)
    at = ((W - img.size[0]) // 2, (W - img.size[1]) // 2 + 2)
    a = Image.new("L", (W, W), 0)
    a.paste(img.getchannel("A"), at)
    ring = a.filter(ImageFilter.MaxFilter(9))
    ink = Image.new("RGBA", (W, W), INK + (255,))
    out = Image.composite(ink, out, ring.point(lambda v: 255 if v > 40 else 0))
    out.alpha_composite(img, at)
    d = ImageDraw.Draw(out)
    d.rounded_rectangle([3, 3, W - 4, W - 4], radius=18, outline=INK + (255,), width=6)
    # clear outside the rounded card
    mask = Image.new("L", (W, W), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, W - 1, W - 1], radius=20, fill=255)
    out.putalpha(ImageChops.multiply(out.getchannel("A"), mask))
    return out.resize((CELL, CELL), Image.LANCZOS)


keys = []
for slot in SLOTS:
    d = os.path.join(CELLS, "gear_" + slot)
    if not os.path.isdir(d):
        continue
    for f in sorted(os.listdir(d)):
        if f.endswith(".png"):
            keys.append((slot, f[:-4].replace("~", ":"), os.path.join(d, f)))
assert len(keys) <= PER * PER, len(keys)
sheet = Image.new("RGBA", (CELL * PER, CELL * PER), (0, 0, 0, 0))
cells = {}
for i, (slot, key, path) in enumerate(keys):
    tile = card(Image.open(path).convert("RGBA"), slot)
    sheet.alpha_composite(tile, ((i % PER) * CELL, (i // PER) * CELL))
    cells[key] = i
sheet.save(os.path.join(OUT, "StyleTiles.png"))
prev = Image.new("RGBA", sheet.size, (70, 74, 88, 255))
prev.alpha_composite(sheet)
prev.save(os.path.join(ROOT, "art", "preview", "style_tiles.png"))
lines = ["-- GENERATED by art/ui/style_tiles.py: do not edit by hand.",
         "-- The gear styles' picture tiles on one 1024 x 1024 sheet of 128 px cells, 8 a row (Config.Ui.styleTiles is",
         "-- its uploaded id; Ui.GearScreen's STYLES tab): each look key (Shared.GearMath.lookKey) -> its cell, from 0.",
         "return {", "\tcell = %d," % CELL, "\tper = %d," % PER, "\tkeys = {"]
for key in sorted(cells):
    lines.append('\t\t["%s"] = %d,' % (key, cells[key]))
lines += ["\t},", "}", ""]
FIT = os.path.join(ROOT, "src", "config", "StyleTiles.luau")
with open(FIT, "w") as fh:
    fh.write("\n".join(lines))
st = shutil.which("stylua") or os.path.expanduser("~/tools/stylua")
if os.path.exists(st):
    subprocess.run([st, "--config-path", os.path.join(ROOT, "stylua.toml"), FIT], check=False)
print("style tiles:", len(cells))
